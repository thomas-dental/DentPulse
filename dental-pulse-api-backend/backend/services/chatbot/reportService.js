// ── Shared TPI fetch ──

/**
 * Cursor-paginated fetch of completed TPIs on a payment plan within a date range.
 * Mirrors useTreatmentInsights so report totals match the Insights page.
 */
async function fetchCompletedTpisForReport(orgId, periodFrom, periodTo, locationId = null, columns = 'tpi_price, tpi_treatment_id, tpi_patient_nomenclature, tpi_payment_plan_id, location_id') {
  const PAGE_SIZE = 1000;
  const out = [];
  let cursor = null;
  const projection = columns.includes('tpi_id') ? columns : `tpi_id, ${columns}`;
  while (true) {
    let q = supabaseAdmin
      .from('treatment_plan_items')
      .select(projection)
      .eq('organization_id', orgId)
      .eq('tpi_completed', true)
      .not('tpi_payment_plan_id', 'is', null)
      .gte('tpi_completed_at', periodFrom)
      .lte('tpi_completed_at', periodTo + 'T23:59:59')
      .order('tpi_id')
      .limit(PAGE_SIZE);
    if (locationId) q = q.eq('location_id', locationId);
    if (cursor != null) q = q.gt('tpi_id', cursor);

    const { data: page, error } = await q;
    if (error) throw error;
    if (!page || page.length === 0) break;
    out.push(...page);
    if (page.length < PAGE_SIZE) break;
    cursor = page[page.length - 1].tpi_id;
  }
  return out;
}

// ── Shared PDF helpers ──

function fmt(val) {
  return '£' + (parseFloat(val) || 0).toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function pct(val) {
  return (parseFloat(val) || 0).toFixed(1) + '%';
}

function addHeader(doc, title, subtitle, periodFrom, periodTo) {
  doc.rect(0, 0, 612, 85).fill('#6c5ce7');
  doc.fontSize(20).font('Helvetica-Bold').fillColor('#ffffff').text(title, 50, 22);
  doc.fontSize(10).font('Helvetica').fillColor('#e0d8ff').text(subtitle, 50, 48);
  doc.fontSize(9).fillColor('#c4bbff')
    .text(`Period: ${formatDateDisplay(periodFrom)} — ${formatDateDisplay(periodTo)}`, 50, 63);
  doc.moveDown(4);
  doc.fillColor('#111827');
}

function addFooter(doc) {
  const y = doc.page.height - 40;
  // Writing below the bottom margin (default 72pt) makes PDFKit insert a new
  // page before placing the text, which is why the footer was landing on a
  // blank page 2. Drop the bottom margin to 0 just for the footer write so
  // the text stays on the page we're finishing.
  const prevBottom = doc.page.margins.bottom;
  doc.page.margins.bottom = 0;
  doc.fontSize(7).font('Helvetica').fillColor('#9ca3af')
    .text(
      `Generated by DentPulse AI  •  ${new Date().toLocaleString('en-GB', { dateStyle: 'long', timeStyle: 'short' })}`,
      50, y,
      { align: 'center', width: 500, lineBreak: false }
    );
  doc.page.margins.bottom = prevBottom;
}

function addSectionTitle(doc, title) {
  if (doc.y > 700) doc.addPage();
  doc.moveDown(0.8);
  doc.fontSize(12).font('Helvetica-Bold').fillColor('#6c5ce7').text(title);
  doc.moveDown(0.3);
  doc.fillColor('#111827');
}

function addTable(doc, headers, rows, colWidths) {
  const startX = 50;
  const totalWidth = colWidths.reduce((s, w) => s + w, 0);
  let y = doc.y;

  // Header row
  doc.rect(startX, y, totalWidth, 20).fill('#f3f0ff');
  doc.fillColor('#374151');
  let x = startX;
  headers.forEach((h, i) => {
    doc.fontSize(8).font('Helvetica-Bold')
      .text(h, x + 4, y + 5, { width: colWidths[i] - 8, align: i === 0 ? 'left' : 'right' });
    x += colWidths[i];
  });
  y += 20;

  // Data rows
  for (let r = 0; r < rows.length; r++) {
    if (y > 720) {
      doc.addPage();
      addFooter(doc);
      y = 50;
    }
    const bg = r % 2 === 0 ? '#ffffff' : '#f9fafb';
    doc.rect(startX, y, totalWidth, 18).fill(bg);
    doc.fillColor('#111827');

    x = startX;
    const row = rows[r];
    row.forEach((cell, i) => {
      const isBold = String(cell).startsWith('£') || String(cell).includes('Total') || String(cell).includes('Net');
      doc.fontSize(8).font(isBold ? 'Helvetica-Bold' : 'Helvetica')
        .text(String(cell), x + 4, y + 4, { width: colWidths[i] - 8, align: i === 0 ? 'left' : 'right' });
      x += colWidths[i];
    });
    y += 18;
  }

  doc.rect(startX, y, totalWidth, 0.5).fill('#e5e7eb');
  doc.y = y + 8;
}

function addKeyValue(doc, label, value, bold) {
  doc.fontSize(10).font('Helvetica-Bold').fillColor('#374151').text(label, { continued: true });
  doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fillColor('#111827').text('  ' + value);
  doc.moveDown(0.2);
}

